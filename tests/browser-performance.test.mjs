import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const text=(a,b)=>{const i=html.indexOf(a),j=html.indexOf(b,i+1);assert.ok(i>=0&&j>i,'Source anchors: '+a);return html.slice(i,j)};
const calls=[];
const state={tempo:120,arp:{rate:8,gate:70,direction:'up',order:'pitch'},slice:{hits:4,rate:8,gate:40},motion:'hold',holdLift:false,steps:[{root:0,quality:'maj'}],selected:0};
const c={state,tone:(...args)=>calls.push(args),voiceNotes:()=>[60,64,67],arpBaseNotes:n=>n,arpNote:(p,i)=>p[i%p.length]};
vm.createContext(c);
vm.runInContext(text('function playVoicing(', 'async function audition('),c);
const play=(mode)=>{calls.length=0;vm.runInContext("playVoicing({root:0,quality:'maj'},0,2,"+JSON.stringify(mode)+",[60,64,67])",c);return calls.slice()};
const arp=play('arp');assert.ok(arp.length>=5&&arp.length<13,'ARP should be a musical 1/8 pattern, not frantic ticks');
assert.ok(arp.some(n=>n[4]===true),'ARP must anchor the pattern with bass');
const slice=play('slice');assert.equal(slice.length,13,'4 repeats of 3 voices, plus one initial bass');
assert.equal(new Set(slice.filter(n=>n[4]===false).map(n=>n[0])).size,3,'SLICE replays full chords, not single melody notes');
assert.ok(slice[3][2]<.2,'SLICE gate should make short rhythmic hits');
state.holdLift=true;const melt=play('hold');assert.ok(melt[0][2]>2,'MELT should sustain through changes');
assert.equal(melt[0][0],60,'MELT must not transpose an octave');
assert.match(html,/release=melt\?2\.7/,'MELT must have long release');
assert.match(html,/chorusWet=ctx\.createGain\(\)/);
assert.match(html,/delayNode=ctx\.createDelay\(2\)/);
assert.match(html,/feedback\.gain\.value=\.29/,'delay feedback must be bounded');
assert.match(html,/setTargetAtTime\(v\?\.35:0,ctx\.currentTime/);
assert.match(html,/data-motion="slice"/);
assert.match(html,/id="slicegate"/);
assert.match(html,/id="cb-delay-time"/);
assert.match(html,/id="wonder"[^>]*type="range"/);
assert.match(html,/addEventListener\('change',\(\)=>\{if\(harmonicVariation\(\)\)/,'SPICE commit must audibly change harmony');
for(const quality of ['m11','maj7sharp11','dom13','sus9','mMaj7','dom7b9']) assert.ok(html.includes(quality+':{\"label\":'),'Missing voicing '+quality);
for(const recipe of ['blue-hour','moonlit-kingdom','dust-and-echoes'])assert.ok(html.includes('data-recipe="'+recipe+'"'),'Missing recipe button '+recipe);
console.log('PASS: chord slicing, arp speed, MELT, chorus/delay gates, spice changes and new harmony palettes.');
